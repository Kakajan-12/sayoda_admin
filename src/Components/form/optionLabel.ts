import { plainText } from "@/Components/ResourceList";

/**
 * Подпись варианта в выпадающем списке.
 *
 * В формах варианты собирались склейкой всех трёх языков:
 * `{title_en} / {title_tk} / {title_ru}`. Значения приходят из полей,
 * которые набирали в редакторе с панелью форматирования, поэтому в списке
 * буквально показывалось
 *
 *   <p>Turkmenistan</p> / <p>Türkmenistan</p> / <p>Туркменистан</p>
 *
 * а у статей вариант доходил до двухсот символов вместе с тегами <strong>
 * посередине. Нативный select переносить текст не умеет — он его обрезает,
 * и отличить один вариант от другого было нельзя.
 *
 * Берём один язык — тот, на котором сейчас интерфейс, — и снимаем разметку.
 * Если перевода нет, отступаем на английский, затем на туркменский: пустая
 * строка в списке хуже чужого языка. Совсем без подписи показываем номер
 * записи, чтобы вариант можно было хотя бы выбрать.
 */
export function optionLabel(row: object, base: string, locale: string): string {
    // Принимаем любой объект: записи справочников описаны своими
    // интерфейсами без индексной сигнатуры, и требовать её от каждого
    // значило бы править десяток типов ради одной подписи.
    const record = row as Record<string, unknown>;
    const pick = (code: string) => plainText(record[`${base}_${code}`] as string);
    return (
        pick(locale) ||
        pick('en') ||
        pick('tk') ||
        pick('ru') ||
        `#${record.id ?? ''}`
    );
}
